from sqlalchemy import Column, Integer, Numeric, String, Text
from app.database.base import Base

class CallLog(Base):
    __tablename__ = "call_logs"

    id = Column(Integer, primary_key=True, index=True)
    customer_id = Column(Integer)
    campaign_id = Column(Integer)
    call_sid = Column(String(255))
    provider = Column(String(32), default="plivo")
    provider_request_id = Column(String(255), nullable=True)
    provider_call_id = Column(String(255), nullable=True, index=True)
    provider_stream_id = Column(String(255), nullable=True)
    provider_recording_id = Column(String(255), nullable=True)
    provider_status = Column(String(64), nullable=True)
    call_status = Column(String(50))
    duration = Column(Integer)
    language = Column(String(20), default="english")
    transcript = Column(Text, nullable=True)
    summary = Column(Text, nullable=True)
    quick_summary = Column(String(500), nullable=True)
    realtime_model = Column(String(100), nullable=True)
    transcription_model = Column(String(100), nullable=True)
    realtime_voice = Column(String(100), nullable=True)
    voice_style_profile = Column(String(80), nullable=True)
    knowledge_profile = Column(String(80), nullable=True)
    conversation_profile = Column(String(80), nullable=True)
    turn_gate_profile = Column(String(80), nullable=True)
    first_response_latency_ms = Column(Integer, nullable=True)
    avg_response_latency_ms = Column(Integer, nullable=True)
    maximum_response_latency_ms = Column(Integer, nullable=True)
    input_audio_tokens = Column(Integer, default=0)
    output_audio_tokens = Column(Integer, default=0)
    input_text_tokens = Column(Integer, default=0)
    output_text_tokens = Column(Integer, default=0)
    estimated_openai_cost_usd = Column(Numeric(12, 6), default=0)
    interruption_count = Column(Integer, default=0)
    false_turn_count = Column(Integer, default=0)
