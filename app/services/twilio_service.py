"""
Twilio service — outbound call management and greeting pre-generation.

Greeting design (fixed from previous version):
The first thing the AI says on a call is FULLY driven by the campaign's
ai_prompt — no hardcoded "Hi, I am calling from DigiDara" script that
ignores the campaign content. The greeting is generated by asking the LLM:
"given this campaign prompt, what do you say when the call first connects?"
"""

import glob
import os
import re
import threading
import time
import uuid
from typing import Optional

import requests
from dotenv import load_dotenv
from requests.exceptions import RequestException, Timeout

from app.services import call_log_service

load_dotenv(
    os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".env")),
    override=True,
)


def _reload_env() -> None:
    load_dotenv(
        os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".env")),
        override=True,
    )


def _normalize_phone(phone: str) -> str:
    """Ensure phone number has a + country-code prefix."""
    phone = phone.strip()
    if phone.startswith("+"):
        return phone
    # Indian 10-digit numbers
    if len(phone) == 10 and phone.isdigit():
        return f"+91{phone}"
    if phone.startswith("91") and len(phone) == 12:
        return f"+{phone}"
    return f"+{phone}"


TAMIL_TTS_SPEAKER = os.getenv("TAMIL_TTS_SPEAKER", "Kore").strip() or "Kore"


def _greeting_suffix(lang: str) -> str:
    if lang == "tamil":
        safe_voice = re.sub(r"[^a-zA-Z0-9_-]+", "", TAMIL_TTS_SPEAKER) or "voice"
        return f"_tamil_{safe_voice}"
    return f"_{lang}"


def start_outbound_call(
    db,
    customer_id: int,
    phone_number: str,
    campaign_id: int,
    sheet_url: Optional[str] = None,
    sheet_row: Optional[int] = None,
) -> dict:
    """
    Places an outbound Twilio call and creates a call_log entry.
    Falls back to simulation mode when Twilio credentials are not configured.
    """
    _reload_env()

    account_sid = os.getenv("TWILIO_ACCOUNT_SID", "")
    auth_token = os.getenv("TWILIO_AUTH_TOKEN", "")
    from_number = os.getenv("TWILIO_PHONE_NUMBER", "")
    webhook_base = (os.getenv("WEBHOOK_BASE_URL") or "").strip().rstrip("/")

    # --- Validate Twilio is configured ---
    placeholders = {"your_twilio_account_sid_here", "your_twilio_auth_token_here", "your_twilio_phone_number_here", ""}
    is_configured = (
        account_sid not in placeholders
        and auth_token not in placeholders
        and from_number not in placeholders
        and bool(webhook_base)
        and "your-tunnel-url" not in webhook_base
    )

    # --- Fetch customer language for pre-generation ---
    cursor = db.cursor()
    cursor.execute("SELECT name, language FROM customers WHERE id = %s", (customer_id,))
    cust = cursor.fetchone()
    selected_lang = (cust.get("language") or "english").lower() if cust else "english"
    if selected_lang not in ["english", "tamil"]:
        selected_lang = "english"
    # The product now has one call path only. This deliberately ignores stale
    # TWILIO_VOICE_ENGINE values from older installations.
    use_openai_realtime = True
    tts_provider = "openai"

    # --- Clear stale greeting cache ---
    audio_dir = os.path.join(os.getcwd(), "audio_cache")
    os.makedirs(audio_dir, exist_ok=True)
    for old_path in glob.glob(os.path.join(audio_dir, f"first_greeting_{customer_id}_{campaign_id}_*")):
        try:
            os.remove(old_path)
        except Exception:
            pass

    # --- Pre-generate greeting audio in background thread ---
    # English calls use ConversationRelay, which generates its greeting as
    # TEXT directly inside the WebSocket handler — no WAV file needed at all.
    # Skipping this saves a Groq + TTS round-trip that was previously wasted.
    # Tamil calls still need the pre-recorded WAV (Gather/Respond flow).
    if selected_lang == "tamil" and not use_openai_realtime:
        threading.Thread(
            target=pregenerate_first_greetings,
            args=(customer_id, campaign_id, selected_lang),
            daemon=True,
        ).start()

    # --- Simulation mode when Twilio not configured ---
    if not is_configured:
        mock_sid = f"mock_call_{int(time.time())}_{uuid.uuid4().hex[:8]}"
        call_log = call_log_service.create_call_log(
            conn=db,
            customer_id=customer_id,
            campaign_id=campaign_id,
            call_sid=mock_sid,
            status="initiated",
            sheet_url=sheet_url,
            sheet_row=sheet_row,
            tts_provider=tts_provider,
            call_path="openai_realtime" if use_openai_realtime else "gather",
        )
        reason = "WEBHOOK_BASE_URL not set or still placeholder" if not webhook_base or "your-tunnel-url" in webhook_base else "Twilio credentials not configured"
        return {
            "message": f"Simulation mode — {reason}. Set real credentials and tunnel URL in .env to place real calls.",
            "call_sid": mock_sid,
            "status": "simulated",
            "log": call_log,
        }

    # --- Real Twilio call ---
    to_number = _normalize_phone(phone_number)
    welcome_url = f"{webhook_base}/voice/welcome?campaign_id={campaign_id}&customer_id={customer_id}"
    status_callback_url = f"{webhook_base}/webhook/twilio"

    try:
        response = requests.post(
            f"https://api.twilio.com/2010-04-01/Accounts/{account_sid}/Calls.json",
            auth=(account_sid, auth_token),
            data=[
                ("To", to_number),
                ("From", from_number),
                ("Url", welcome_url),
                ("Method", "POST"),
                ("StatusCallback", status_callback_url),
                ("StatusCallbackEvent", "initiated"),
                ("StatusCallbackEvent", "ringing"),
                ("StatusCallbackEvent", "answered"),
                ("StatusCallbackEvent", "completed"),
                ("StatusCallbackMethod", "POST"),
                ("Record", "true"),
                ("RecordingChannels", "dual"),
                ("RecordingTrack", "both"),
                ("RecordingStatusCallback", f"{webhook_base}/webhook/twilio/recording"),
                ("RecordingStatusCallbackMethod", "POST"),
            ],
            timeout=10,
        )

        if response.status_code in (200, 201):
            resp_json = response.json()
            call_sid = resp_json.get("sid") or f"twilio_{uuid.uuid4().hex[:8]}"
            call_path = "openai_realtime"
            call_log = call_log_service.create_call_log(
                conn=db,
                customer_id=customer_id,
                campaign_id=campaign_id,
                call_sid=call_sid,
                status="initiated",
                sheet_url=sheet_url,
                sheet_row=sheet_row,
                call_path=call_path,
                tts_provider=tts_provider,
            )
            return {
                "message": "Call initiated successfully",
                "call_sid": call_sid,
                "status": "initiated",
                "log": call_log,
            }
        else:
            call_sid = f"failed_{uuid.uuid4().hex[:8]}"
            call_log_service.create_call_log(
                conn=db, customer_id=customer_id, campaign_id=campaign_id,
                call_sid=call_sid, status="failed",
                sheet_url=sheet_url, sheet_row=sheet_row,
                tts_provider=tts_provider,
            )
            return {
                "message": f"Twilio API error {response.status_code}: {response.text[:300]}",
                "call_sid": call_sid,
                "status": "failed",
            }

    except Timeout:
        call_sid = f"timeout_{uuid.uuid4().hex[:8]}"
        call_log_service.create_call_log(
            conn=db, customer_id=customer_id, campaign_id=campaign_id,
            call_sid=call_sid, status="failed",
            sheet_url=sheet_url, sheet_row=sheet_row,
            tts_provider=tts_provider,
        )
        return {"message": "Twilio API request timed out after 10 seconds.", "call_sid": call_sid, "status": "failed"}

    except RequestException as e:
        call_sid = f"error_{uuid.uuid4().hex[:8]}"
        call_log_service.create_call_log(
            conn=db, customer_id=customer_id, campaign_id=campaign_id,
            call_sid=call_sid, status="failed",
            sheet_url=sheet_url, sheet_row=sheet_row,
            tts_provider=tts_provider,
        )
        return {"message": f"Network error contacting Twilio: {e}", "call_sid": call_sid, "status": "failed"}


def _build_greeting_prompt(
    base_prompt: str,
    customer_name: str,
    investigated_course: Optional[str],
    internship_or_course: Optional[str],
    course_duration: Optional[str],
    lang: str,
) -> tuple:
    """
    Builds a greeting-specific system prompt + trigger message.
    The campaign's ai_prompt is the source of truth — no hardcoded overrides.
    """
    prompt = base_prompt
    for ph, val in [
        ("{customer_name}", customer_name),
        ("{name}", customer_name),
        ("{customer_language}", lang),
        ("{language}", lang),
    ]:
        prompt = prompt.replace(ph, str(val))

    if lang == "tamil":
        course_info = ""
        if investigated_course:
            ioc = internship_or_course or "பயிற்சி"
            dur = f" ({course_duration})" if course_duration else ""
            course_info = f"நீங்கள் {investigated_course} {ioc}{dur} பற்றி விசாரித்திருந்தீர்கள். "

        greeting_instruction = (
            f"\n\nவாழ்த்து வழிகாட்டி:\n"
            f"நீங்கள் {customer_name} அவர்களுக்கு டிஜிடாரா டெக்னாலஜி சார்பாக முதல் முறை அழைக்கிறீர்கள்.\n"
            f"உங்கள் முதல் வாக்கியம்: 'வணக்கம் {customer_name}, நான் டிஜிடாரா டெக்னாலஜி சார்பாக அழைக்கிறேன்.'\n"
            f"பிறகு உடனே: {course_info}Campaign prompt-ல் சொன்னதை natural-ஆக தமிழில் சொல்லுங்கள்.\n"
            f"2-3 வாக்கியங்களில் முடிக்கவும். பேச்சு வழக்கு தமிழில் மட்டும். Markdown வேண்டாம்.\n"
        )
        prompt += greeting_instruction
        trigger = "வணக்கம், நான் கேட்கிறேன்."
    else:
        course_info = ""
        if investigated_course:
            ioc = internship_or_course or "course/internship"
            dur = f" of {course_duration}" if course_duration else ""
            course_info = f"They enquired about {ioc} in {investigated_course}{dur}. "

        greeting_instruction = (
            f"\n\nGREETING GUIDE:\n"
            f"You are making first contact with {customer_name} on behalf of DigiDara Technologies.\n"
            f"Your opening MUST:\n"
            f"1. Start with: 'Hi {customer_name}, I'm calling from DigiDara Technologies.'\n"
            f"2. Then immediately say what you're calling about (from the campaign prompt above).\n"
            f"{course_info}"
            f"3. End with the campaign's opening question.\n"
            f"Keep it to 2-3 natural sentences. Warm, friendly tone. No markdown. Plain text only.\n"
        )
        prompt += greeting_instruction
        trigger = "Hello, I'm listening."

    return prompt, trigger


def pregenerate_first_greetings(
    customer_id: int,
    campaign_id: int,
    selected_lang: Optional[str],
) -> None:
    """
    Pre-generates greeting TTS audio in a background thread.
    The greeting is fully driven by the campaign's ai_prompt.
    """
    from app.database.db import get_db_connection
    from app.services import campaign_service
    from app.services.groq_service import generate_response
    from app.services.gemini_service import text_to_speech

    db = get_db_connection()
    try:
        cursor = db.cursor()
        cursor.execute(
            "SELECT name, investigated_course, internship_or_course, course_duration FROM customers WHERE id = %s",
            (customer_id,),
        )
        cust = cursor.fetchone()
        customer_name = (cust.get("name") or "").strip() if cust else "Customer"
        if not customer_name:
            customer_name = "Customer"
        investigated_course = cust.get("investigated_course") if cust else None
        internship_or_course = cust.get("internship_or_course") if cust else None
        course_duration = cust.get("course_duration") if cust else None

        campaign = campaign_service.get_campaign_by_id(db, campaign_id)
        if not campaign:
            print(f"[Greeting] Campaign {campaign_id} not found — skipping pre-generation.")
            return
        base_prompt = campaign.get("ai_prompt") or "You are a helpful DigiDara assistant."

        audio_dir = os.path.join(os.getcwd(), "audio_cache")
        os.makedirs(audio_dir, exist_ok=True)

        langs_to_generate = [selected_lang] if selected_lang else ["english", "tamil"]

        for lang in langs_to_generate:
            if not lang:
                continue
            lang = lang.lower()
            if lang not in ["english", "tamil"]:
                lang = "english"

            lang_code = "ta-IN" if lang == "tamil" else "en-IN"
            suffix = _greeting_suffix(lang)
            wav_path = os.path.join(audio_dir, f"first_greeting_{customer_id}_{campaign_id}{suffix}.wav")
            txt_path = os.path.join(audio_dir, f"first_greeting_{customer_id}_{campaign_id}{suffix}.txt")

            if os.path.exists(wav_path):
                continue  # already generated (concurrent write protection)

            try:
                greeting_prompt, trigger = _build_greeting_prompt(
                    base_prompt, customer_name,
                    investigated_course, internship_or_course, course_duration, lang,
                )
                greeting_text = (generate_response(greeting_prompt, trigger, []) or "").strip()

                if not greeting_text:
                    greeting_text = (
                        f"Hi {customer_name}, I'm calling from DigiDara Technologies."
                        if lang == "english"
                        else f"வணக்கம் {customer_name}, நான் டிஜிடாரா டெக்னாலஜி சார்பாக அழைக்கிறேன்."
                    )

                with open(txt_path, "w", encoding="utf-8") as f:
                    f.write(greeting_text)

                # English → ElevenLabs (faster, better voice quality)
                # Tamil → Gemini
                if lang == "english":
                    try:
                        from app.services.elevenlabs_service import text_to_speech_elevenlabs
                        audio_bytes = text_to_speech_elevenlabs(greeting_text)
                    except Exception as el_err:
                        print(f"[Greeting] ElevenLabs failed, using configured legacy fallback: {el_err}")
                        audio_bytes = text_to_speech(greeting_text, language_code=lang_code)
                else:
                    audio_bytes = text_to_speech(
                        greeting_text,
                        language_code=lang_code,
                        speaker=TAMIL_TTS_SPEAKER,
                    )

                with open(wav_path, "wb") as f:
                    f.write(audio_bytes)

                print(f"[Greeting] customer={customer_id} campaign={campaign_id} lang={lang}: '{greeting_text[:100]}'")

            except Exception as e:
                print(f"[Greeting] Failed for lang={lang}: {e}")

    except Exception as err:
        print(f"[Greeting] Outer error: {err}")
    finally:
        db.close()


def trigger_next_queued_call(sheet_url: str, campaign_id: int) -> None:
    from app.database.db import get_db_connection
    from app.services import google_sheets_service, customer_service

    db = get_db_connection()
    try:
        rows = google_sheets_service.read_sheet_data(sheet_url)
        if not rows:
            print(f"[Queue] No rows found in sheet {sheet_url}")
            return

        for i, row in enumerate(rows):
            status_val = (row.get("Status") or row.get("status") or "").strip().lower()
            if status_val not in ("queued", "queue", "pending", ""):
                continue

            row_index = i + 2
            name = row.get("Name") or row.get("name") or ""
            phone = row.get("Phone") or row.get("phone") or ""
            language = (row.get("Language") or row.get("language") or "english").lower()
            investigated_course = row.get("Investigated Course") or row.get("investigated_course") or ""
            internship_or_course = row.get("Internship or Course") or row.get("internship_or_course") or ""
            course_duration = row.get("Course Duration") or row.get("course_duration") or ""

            if not phone:
                print(f"[Queue] Row {row_index} has no phone number, skipping.")
                continue

            customer_id = customer_service.upsert_customer(
                db, name=name, phone=phone, language=language,
                investigated_course=investigated_course,
                internship_or_course=internship_or_course,
                course_duration=course_duration,
                sheet_url=sheet_url, sheet_row=row_index,
            )
            google_sheets_service.update_sheet_status(sheet_url, row_index, "calling")
            result = start_outbound_call(db, customer_id, phone, campaign_id, sheet_url, row_index)
            print(f"[Queue] Row {row_index}: {result}")
            break  # only trigger one at a time

    except Exception as e:
        print(f"[Queue] Error: {e}")
    finally:
        db.close()
